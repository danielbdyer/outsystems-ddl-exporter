using System;
using System.Collections.Generic;
using System.Linq;
using static DbChange.Kernel.Tests.KernelProperties;

namespace DbChange.Kernel.Tests;

/// <summary>
/// The elements a schema is written as, in the shapes io/Ssdt.ReadModel reads from DacFx 170.5.96 on a published copy (measured on the
/// golden project with the sample change declare-what-the-planter-reads): a table's Columns in ordinal order, its Schema and its
/// TemporalSystemVersioningHistoryTable; a column's facets, Nullable, IsIdentity with IdentitySeed and IdentityIncrement as text,
/// Expression, Persisted and PersistedNullable, GeneratedAlwaysType, Sparse and IsRowGuidCol, and its DataType (none for a computed
/// column); an alias's DataType element with its Uddt facets and its Type; a key's Columns with Columns[i].Ascending; a foreign key's
/// Columns, ForeignColumns, ForeignTable and actions; a check's and a default's Expression, a default's TargetColumn and the Sequence its
/// ExpressionDependencies name; a trigger's TriggerObject and TriggerType; each one's Host or IndexedObject. Schema.Of reads them back,
/// so its reading rules are pinned to these shapes.
/// </summary>
internal static class SchemaElements
{
    public static SortedArray<Element> Of(Schema schema)
    {
        var elements = new List<Element>();
        var (schemas, aliases, sequences) = (new SortedSet<string>(StringComparer.Ordinal), new Dictionary<Name, ColumnType>(),
            new SortedSet<Name>());
        foreach (var table in schema.Tables)
        {
            var key = Ok(ElementKey.Of("Table", table.Name));
            ElementKey ColumnKey(Name column) => Key(key, "Column", column.Base);
            schemas.Add(table.Name.Schema!);
            elements.Add(New(key, [("IsAutoGeneratedHistoryTable", Bool(false)), ("MemoryOptimized", Bool(false))],
            [
                ("Columns", [.. table.Columns.Select(c => ColumnKey(c.Name))]), ("Schema", [SchemaKey(table.Name.Schema!)]),
                ("TemporalSystemVersioningHistoryTable", table.Versioning is Versioning.Current current ? [TableKey(current.HistoryTable)] : []),
            ]));
            foreach (var column in table.Columns)
            {
                elements.Add(Column(ColumnKey(column.Name), column, key, aliases));
                if (column is Column.Stored { Default: { } d })
                {
                    elements.Add(DefaultOf(d, key, ColumnKey(column.Name)));
                    sequences.UnionWith(d.Sequence is { } s ? [s] : []);
                }
            }

            if (table.Key is { } pk)
            {
                elements.Add(New(pk.Constraint is { } name ? Ok(ElementKey.Of("PrimaryKeyConstraint", name))
                        : Key(key, "PrimaryKeyConstraint", "Host"),
                    [("Clustered", Bool(pk.Clustered)), ("Disabled", Bool(false)), .. Ascending(pk.Columns)],
                    [("Columns", [.. pk.Columns.Select(c => ColumnKey(c.Column))]), ("Host", [key])]));
            }

            elements.AddRange(table.Uniques.Select(u => u.IsIndex
                ? New(u.Key, [("Clustered", Bool(false)), ("Disabled", Bool(u.Disabled)),
                        ("FilterPredicate", u.Filter ?? (Value)new Value.Null()), ("Unique", Bool(true)), .. Ascending(u.Columns)],
                    [("Columns", [.. u.Columns.Select(c => ColumnKey(c.Column))]), ("IndexedObject", [key])])
                : New(u.Key, [("Clustered", Bool(false)), ("Disabled", Bool(u.Disabled)), .. Ascending(u.Columns)],
                    [("Columns", [.. u.Columns.Select(c => ColumnKey(c.Column))]), ("Host", [key])])));
            elements.AddRange(table.References.Select(r => New(r.Key,
                [("DeleteAction", Action(r.OnDelete)), ("Disabled", Bool(r.Disabled)), ("NotForReplication", Bool(false)),
                    ("UpdateAction", Action(r.OnUpdate))],
                [
                    ("Columns", [.. r.Legs.Select(l => ColumnKey(l.Column))]),
                    ("ForeignColumns", [.. r.Legs.Select(l => Key(TableKey(r.Parent), "Column", l.ParentColumn.Base))]),
                    ("ForeignTable", [TableKey(r.Parent)]), ("Host", [key]),
                ])));
            elements.AddRange(table.Checks.Select(c => New(c.Key, [("Disabled", Bool(c.Disabled)), ("Expression", c.Expression)],
                [("ExpressionDependencies", c.Key.Parent is { Type: "Column" } column ? [column] : []), ("Host", [key])])));
            elements.AddRange(table.Triggers.Select(t => New(Ok(ElementKey.Of("DmlTrigger", t.Name)),
                [("Definition", new Value.Script("CREATE TRIGGER " + t.Name + " ON " + table.Name + " AFTER INSERT AS SET NOCOUNT ON;")),
                    ("Disabled", Bool(t.Disabled)),
                    ("TriggerType", new Value.Enumeration("TriggerType", t.InsteadOf ? "InsteadOf" : "After"))],
                [("TriggerObject", [key])])));
        }

        elements.AddRange(schemas.Select(s => New(SchemaKey(s), [])));
        elements.AddRange(aliases.Select(a => New(Ok(ElementKey.Of("DataType", a.Key)),
            [("SqlDataType", new Value.Enumeration("SqlDataType", "Unknown")), ("UddtIsMax", Bool(a.Value.IsMax)),
                ("UddtLength", Int(a.Value.Length)), ("UddtNullable", Bool(false)), ("UddtPrecision", Int(a.Value.Precision)),
                ("UddtScale", Int(a.Value.Scale))],
            [("Schema", [SchemaKey(a.Key.Schema!)]), ("Type", [Ok(ElementKey.Of("DataType", a.Value.Type))])])));
        elements.AddRange(sequences.Select(s => New(Ok(ElementKey.Of("Sequence", s)), [("StartValue", Text("5000"))],
            [("DataType", [Ok(ElementKey.Of("DataType", Ok(Name.Of("int"))))]), ("Schema", [SchemaKey(s.Schema!)])])));
        return SortedArray.Of(elements);
    }

    public static ElementKey TableKey(Name table) => Ok(ElementKey.Of("Table", table));

    private static ElementKey SchemaKey(string schema) => Ok(ElementKey.Of("Schema", Ok(Name.Of(schema))));

    private static Value Action(ReferentialAction action) => new Value.Enumeration("ForeignKeyAction", action.ToString());

    private static IEnumerable<(string, Value)> Ascending(SortedArray<KeyColumn> columns) =>
        columns.Select(c => ("Columns[" + c.Position + "].Ascending", Bool(!c.Descending)));

    private static Element DefaultOf(Default d, ElementKey table, ElementKey column) =>
        New(d.Constraint is { } name ? Ok(ElementKey.Of("DefaultConstraint", name)) : Key(column, "DefaultConstraint", "TargetColumn"),
            [("Disabled", Bool(false)), ("Expression", d.Expression), ("WithValues", Bool(false))],
            [("ExpressionDependencies", d.Sequence is { } s ? [Ok(ElementKey.Of("Sequence", s))] : []), ("Host", [table]),
                ("TargetColumn", [column])]);

    /// <summary>A column's element: every property DacFx gives a column, valued as a copy's reads.</summary>
    private static Element Column(ElementKey key, Column column, ElementKey table, Dictionary<Name, ColumnType> aliases)
    {
        var (type, alias) = column.Match<(ColumnType?, Name?)>(s => (s.Type, s.Alias), _ => (null, null), g => (g.Type, null));
        if (alias is { } a)
        {
            aliases[a] = type! with { Collation = null };
        }

        var facets = alias is null ? type : type! with { Length = 0, IsMax = false, Precision = 0, Scale = 0 };
        var stored = column as Column.Stored;
        var computed = column as Column.Computed;
        var generated = (column as Column.Generated)?.As switch
        {
            GeneratedAs.RowStart => "GeneratedAlwaysAsRowStart",
            GeneratedAs.RowEnd => "GeneratedAlwaysAsRowEnd",
            GeneratedAs.Other => "GeneratedAlwaysAsTransactionIdStart",
            _ => "None",
        };
        return New(key,
        [
            ("Collation", facets?.Collation is { } collation ? Text(collation) : new Value.Null()),
            ("Expression", computed?.Expression ?? (Value)new Value.Null()),
            ("GeneratedAlwaysType", new Value.Enumeration("ColumnGeneratedAlwaysType", generated)),
            ("IdentityIncrement", Text((stored?.Identity?.Increment ?? 1).ToString(System.Globalization.CultureInfo.InvariantCulture))),
            ("IdentitySeed", Text((stored?.Identity?.Seed ?? 1).ToString(System.Globalization.CultureInfo.InvariantCulture))),
            ("IsIdentity", Bool(stored?.Identity is not null)), ("IsMax", Bool(facets?.IsMax ?? false)),
            ("IsRowGuidCol", Bool(stored?.RowGuid ?? false)), ("Length", Int(facets?.Length ?? 0)),
            ("Nullable", Bool(computed is { Persisted: true } || column.Nullable)), ("Persisted", Bool(computed?.Persisted ?? false)),
            ("PersistedNullable", computed is { Persisted: true } ? Bool(column.Nullable) : new Value.Null()),
            ("Precision", Int(facets?.Precision ?? 0)), ("Scale", Int(facets?.Scale ?? 0)), ("Sparse", Bool(stored?.Sparse ?? false)),
        ],
        [
            ("DataType", type is null ? [] : [Ok(ElementKey.Of("DataType", alias ?? type.Type))]),
            ("ExpressionDependencies", computed is null ? [] : [Key(table, "Column", "Id")]),
        ]);
    }
}
