#!/usr/bin/env node
// Package the ssdt-agent tree as Claude Code skills/agents — apply | check.
//
// CONNECTORS.md §1, executed with the repo's regenerate-and-diff discipline
// instead of raw copies: each packaged entry is a POINTER SKILL — the source
// SKILL.md's frontmatter verbatim (the `description` is the dispatch surface
// Claude Code triggers on) plus a one-line body that routes to the canonical
// in-tree file. One canonical body, working relative citations, no drift
// surface beyond the frontmatter — and the `packaging` gate
// (ssdt-agent-gates.mjs) fails CI whenever source and package disagree.
//
//   apply   (re)generate .claude/skills/<name>/SKILL.md for every
//           ssdt-agent/skills/**/SKILL.md, and .claude/agents/<name>.md for
//           every ssdt-agent/agents/*.md
//   check   exit 1 if the packaged set is missing, stale, or orphaned
//
// `skills/operations/*.md` are knowledge files, not skills, and are never
// packaged (CONNECTORS.md §1's explicit carve-out).
//
// Node ≥ 18, zero dependencies. Run from anywhere; paths resolve from this
// file's location.

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative, basename } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const PROJ = dirname(HERE);                    // sidecar/projection
const REPO = dirname(dirname(PROJ));           // repo root
const TREE = join(PROJ, "ssdt-agent");
const DOT = join(REPO, ".claude");

const FRONT = /^---\n([\s\S]*?\n)---\n/;

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

function* sources() {
  for (const p of walk(join(TREE, "skills")).filter((p) => basename(p) === "SKILL.md").sort()) {
    yield { kind: "skill", name: basename(dirname(p)), src: p, rel: relative(REPO, p) };
  }
  for (const p of walk(join(TREE, "agents")).filter((p) => p.endsWith(".md")).sort()) {
    yield { kind: "agent", name: basename(p, ".md"), src: p, rel: relative(REPO, p) };
  }
}

function frontmatter(path) {
  const m = FRONT.exec(readFileSync(path, "utf8"));
  if (!m) { console.error(`no frontmatter in ${path}`); process.exit(1); }
  return m[1];
}

function rendered({ kind, src, rel }) {
  const fm = frontmatter(src);
  const body =
    kind === "skill"
      ? `The canonical skill body lives in the tree, where its relative citations resolve:\n` +
        `**Read \`${rel}\` now and follow it exactly.** This package is the dispatch pointer\n` +
        `(generated by \`sidecar/projection/scripts/ssdt-agent-package.mjs apply\`; do not edit by hand).\n`
      : `Adopt the role defined at \`${rel}\` — **Read that file now and follow it exactly**,\n` +
        `then proceed with the task you were given. This package is the dispatch pointer\n` +
        `(generated by \`sidecar/projection/scripts/ssdt-agent-package.mjs apply\`; do not edit by hand).\n`;
  return `---\n${fm}---\n\n${body}`;
}

function target({ kind, name }) {
  return kind === "skill" ? join(DOT, "skills", name, "SKILL.md") : join(DOT, "agents", name + ".md");
}

// --------------------------------------------------------------------------
// Copilot target (GitHub Copilot in Visual Studio, for the estate repo)
//
// CONNECTORS.md §2. The team develops in GitHub Copilot inside Visual Studio,
// against an Azure DevOps SSDT repository that does NOT contain this monorepo's
// sidecar/projection/ssdt-agent/ path. So the Copilot bundle assumes the whole
// canonical tree is VENDORED at `ssdt-agent/` in the estate repo root, and every
// pointer routes there (vendoring the whole tree keeps its internal cross-
// references resolving). The bundle is generated into ssdt-agent/copilot-package/
// and copied, with the vendored tree, into the estate repo. See ADOPTION.md.
//
//   copilot-apply   (re)generate ssdt-agent/copilot-package/
//   copilot-check   exit 1 if that bundle is missing, stale, or orphaned
// --------------------------------------------------------------------------

const COPILOT = join(TREE, "copilot-package");
const VENDOR = "ssdt-agent"; // where the tree is vendored in the estate repo root
const GEN =
  "<!-- Generated by sidecar/projection/scripts/ssdt-agent-package.mjs copilot-apply. " +
  "Do not edit by hand; edit the generator and re-run. -->";

function copilotSkill({ src }) {
  const relTree = relative(TREE, src); // e.g. skills/op/make-mandatory/SKILL.md
  const body = [
    GEN, "",
    "The full skill lives in the vendored tree, where its cross-references resolve.",
    "**Read `" + VENDOR + "/" + relTree + "` (from the repository root) and follow it exactly.**",
    "This file is only the dispatch pointer Copilot matches on; the skill body is in the tree.",
  ].join("\n");
  return `---\n${frontmatter(src)}---\n\n${body}\n`;
}

function copilotAgent({ src }) {
  const relTree = relative(TREE, src); // e.g. agents/intake.md
  // Copilot custom-agent frontmatter is the source name + description, verbatim.
  // `tools` and `model` are intentionally omitted: Visual Studio tool names vary by
  // build and are unverified here, so the agent uses the default toolset. ADOPTION.md
  // records how to restrict tools once the team confirms their build's names.
  const body = [
    GEN, "",
    "Adopt this role. The full role definition lives in the vendored tree.",
    "**Read `" + VENDOR + "/" + relTree + "` (from the repository root) and follow it exactly**, then",
    "proceed with the task you were given. This file is only the agent Copilot loads.",
  ].join("\n");
  return `---\n${frontmatter(src)}---\n\n${body}\n`;
}

