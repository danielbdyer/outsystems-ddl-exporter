// Estate-kit target (the machine scripts + acceptance catalog + bake pipeline
// the estate repository consumes)
//
// PROVING_SURFACE_DESIGN §5 / plan slice C12. Sources live at
// scripts/estate-kit/ (developed and proven in the monorepo); the committed
// bundle is generated into ssdt-agent/estate-kit/ so the vendor drop carries
// it at a tree-rooted path. The generation is a transform, not a copy: the
// sqlpackage pin is BAKED from the toolchain ledger over the
// __SQLPACKAGE_PIN__ placeholder (so a late pinning propagates by re-apply,
// and pin drift fails the packaging gate), a generation marker lands in
// every file whose syntax carries comments, and the kit's ADOPTION.md +
// twin.starter.json are generated here.
//
//   estate-kit-apply   (re)generate ssdt-agent/estate-kit/
//   estate-kit-check   exit 1 if that bundle is missing, stale, or orphaned
// --------------------------------------------------------------------------

const KIT_SRC = join(HERE, "estate-kit");
const KIT_OUT = join(TREE, "estate-kit");
const KIT_MARK =
  "Generated by sidecar/projection/scripts/ssdt-agent-package.mjs estate-kit-apply " +
  "(ssdt-agent-package). Do not edit by hand; edit scripts/estate-kit/ and re-run.";

function toolchainPin(rowLabel) {
  const ledger = readFileSync(join(TREE, "estate", "toolchain.md"), "utf8");
  for (const line of ledger.split("\n")) {
    const cells = line.split("|").map((c) => c.trim());
    if (cells[1] === rowLabel && cells[2]) return cells[2];
  }
  return "UNPINNED";
}

function eolOf(text) {
  return text.includes("\r\n") ? "\r\n" : "\n";
}

// Insert the generation marker in the file's own comment syntax, preserving
// its line-ending convention. JSON carries no comments, so a JSON file rides
// unmarked (the expected-set comparison still governs it; only the orphan
// scan cannot see it).
function withKitMarker(rel, content) {
  const eol = eolOf(content);
  const lines = content.split(eol);
  const insert = (at, markerLine) => {
    lines.splice(at, 0, markerLine);
    return lines.join(eol);
  };
  if (rel.endsWith(".sh")) return insert(lines[0]?.startsWith("#!") ? 1 : 0, `# ${KIT_MARK}`);
  if (rel.endsWith(".ps1")) return insert(0, `# ${KIT_MARK}`);
  if (rel.endsWith(".sql")) return insert(0, `-- ${KIT_MARK}`);
  if (rel.endsWith(".yml") || rel.endsWith(".yaml")) return insert(0, `# ${KIT_MARK}`);
  if (rel.endsWith(".xml") || rel.endsWith(".sqlproj"))
    return insert(lines[0]?.startsWith("<?xml") ? 1 : 0, `<!-- ${KIT_MARK} -->`);
  return content;
}

