#!/usr/bin/env node
// Package the ssdt-agent tree as Claude Code skills/agents — apply | check.
//
// CONNECTORS.md §1, executed with the repo's regenerate-and-diff discipline
// instead of raw copies: each packaged entry is a POINTER SKILL — the source
// SKILL.md's frontmatter verbatim (the `description` is the dispatch surface
// Claude Code triggers on) plus a one-line body that routes to the canonical
// in-tree file. One canonical body, working relative citations, no drift
// surface beyond the frontmatter — and the `packaging` gate
// (ssdt-agent-gates.mjs) fails CI whenever source and package disagree.
//
//   apply   (re)generate .claude/skills/<name>/SKILL.md for every
//           ssdt-agent/skills/**/SKILL.md, and .claude/agents/<name>.md for
//           every ssdt-agent/agents/*.md
//   check   exit 1 if the packaged set is missing, stale, or orphaned
//
// `skills/operations/*.md` are knowledge files, not skills, and are never
// packaged (CONNECTORS.md §1's explicit carve-out).
//
// Node ≥ 18, zero dependencies. Run from anywhere; paths resolve from this
// file's location.

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync, rmSync } from "node:fs";
import { dirname, join, relative, basename, normalize, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const HERE = dirname(fileURLToPath(import.meta.url));
const PROJ = dirname(HERE);                    // sidecar/projection
const REPO = dirname(dirname(PROJ));           // repo root
const TREE = join(PROJ, "ssdt-agent");
const DOT = join(REPO, ".claude");

const FRONT = /^---\n([\s\S]*?\n)---\n/;

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

function* sources() {
  for (const p of walk(join(TREE, "skills")).filter((p) => basename(p) === "SKILL.md").sort()) {
    yield { kind: "skill", name: basename(dirname(p)), src: p, rel: relative(REPO, p) };
  }
  for (const p of walk(join(TREE, "agents")).filter((p) => p.endsWith(".md")).sort()) {
    yield { kind: "agent", name: basename(p, ".md"), src: p, rel: relative(REPO, p) };
  }
}

function frontmatter(path) {
  const m = FRONT.exec(readFileSync(path, "utf8"));
  if (!m) { console.error(`no frontmatter in ${path}`); process.exit(1); }
  return m[1];
}

function rendered({ kind, src, rel }) {
  const fm = frontmatter(src);
  const body =
    kind === "skill"
      ? `The canonical skill body lives in the tree, where its relative citations resolve:\n` +
        `**Read \`${rel}\` now and follow it exactly.** This package is the dispatch pointer\n` +
        `(generated by \`sidecar/projection/scripts/ssdt-agent-package.mjs apply\`; do not edit by hand).\n`
      : `Adopt the role defined at \`${rel}\` — **Read that file now and follow it exactly**,\n` +
        `then proceed with the task you were given. This package is the dispatch pointer\n` +
        `(generated by \`sidecar/projection/scripts/ssdt-agent-package.mjs apply\`; do not edit by hand).\n`;
  return `---\n${fm}---\n\n${body}`;
}

function target({ kind, name }) {
  return kind === "skill" ? join(DOT, "skills", name, "SKILL.md") : join(DOT, "agents", name + ".md");
}

