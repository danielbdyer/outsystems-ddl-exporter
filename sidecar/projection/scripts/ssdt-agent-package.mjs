// --------------------------------------------------------------------------
// Vendor channel (the curated tree the estate repository vendors)
//
// PROVING_SURFACE_DESIGN §5 decision (i). The vendor SET is the tree the
// estate consumes — the skills, agents, ledgers, proving ground, self-test,
// worked examples, the record standards, the Windows path, the runbook, the
// Copilot bundle, and the estate kit — and deliberately NOT the monorepo's
// program documents (assessments, handoffs, design and plan documents, the
// Claude Code router), whose citations reach the monorepo. `vendor-check`
// proves the drop CITATION-CLOSED: every backticked relative path and bare
// .md citation in the drop's documents resolves inside the drop, because the
// estate repository has no monorepo around it. `vendor-apply` stages the
// drop (gitignored; `publish-to-estate.sh` syncs it into an estate clone)
// with a VENDOR.json naming the source commit.
//
//   vendor-apply [dest]   stage the drop (default ssdt-agent/vendor-drop/)
//   vendor-check          exit 1 if the drop set is broken or not closed
// --------------------------------------------------------------------------

const VENDOR_DIRS = [
  "skills", "agents", "estate", "proving-ground", "self-test", "sample-prs",
  "copilot-package", "estate-kit",
];
const VENDOR_FILES = [
  "README.md", "THE_RECORD.md", "THE_RECORD_FORMS.md", "THE_DECISION_TREE.md",
  "FINDINGS_AND_CHANGES.md", "PROVING_PATH_WINDOWS.md", "CAPTURE_POINT_RUNBOOK.md",
];
// Working artifacts under the vendored dirs that never ship.
const VENDOR_SKIP = /(^|[\\/])(bin|obj|templates|logs)([\\/]|$)|\.dacpac$|(^|[\\/])delta[^\\/]*\.sql$/;

function vendorSet() {
  const files = new Map(); // drop-relative -> absolute source
  for (const dir of VENDOR_DIRS) {
    for (const p of walk(join(TREE, dir))) {
      const rel = relative(TREE, p);
      if (VENDOR_SKIP.test(rel)) continue;
      files.set(rel, p);
    }
  }
  for (const f of VENDOR_FILES) {
    const p = join(TREE, f);
    if (existsSync(p)) files.set(f, p);
  }
  return files;
}

const DROP_REL_PATH = /`((?:\.\.\/)*[\w./ -]+?(?:\.(?:md|sql|xml|json|refactorlog|sh|ps1|yml|sqlproj)|\/))`/g;
const DROP_BARE_MD = /`([A-Za-z0-9][\w. -]*?\.md)`/g;

// The closure rule, stated precisely. A backticked PATH citation (it contains
// a slash) that RESOLVES IN THE MONOREPO — from the citing file's directory,
// or from the tree root (the tree's own root-relative convention) — must also
// resolve INSIDE the drop, because the estate repository has no monorepo
// around it; one that resolves nowhere in the monorepo either is a contextual
// fragment (a scratch-copy path, an estate-repo path), not a link, and is not
// judged here. A BARE .md filename is a mention by name, not a path: it is
// typo-checked against the drop plus the monorepo's known documents (the
// citations gate's own R2 universe), and a known monorepo document mentioned
// as provenance does not break closure.
function vendorClosureProblems(files) {
  const problems = [];
  const present = new Set([...files.keys()].map((r) => r.replaceAll("\\", "/")));
  const basenames = new Set([...files.keys()].map((r) => basename(r)));
  const known = new Set(basenames);
  for (const root of [TREE, join(REPO, "handbook"), join(REPO, "ssdt-playbook")]) {
    for (const f of walk(root)) if (f.endsWith(".md")) known.add(basename(f));
  }
  for (const name of readdirSync(PROJ)) if (name.endsWith(".md")) known.add(name);
  const inDrop = (dropRel) => {
    const t = dropRel.replaceAll("\\", "/").replace(/\/$/, "");
    return present.has(t) || [...present].some((f) => f.startsWith(t + "/"));
  };
  for (const [rel, src] of [...files].sort()) {
    if (!rel.endsWith(".md")) continue;
    // The Copilot bundle's citations are estate-repo-root-relative by design
    // (they resolve after vendoring); copilot-check owns that bundle.
    if (rel.replaceAll("\\", "/").startsWith("copilot-package/")) continue;
    const text = readFileSync(src, "utf8");
    const dir = dirname(rel);
    for (const m of text.matchAll(DROP_REL_PATH)) {
      if (!m[1].includes("/")) continue;
      const fromDir = normalize(join(dir, m[1]));
      const fromRoot = normalize(m[1]);
      if (inDrop(fromDir) || inDrop(fromRoot)) continue;
      const resolvesInMonorepo =
        existsSync(normalize(join(dirname(src), m[1]))) || existsSync(normalize(join(TREE, m[1])));
      if (resolvesInMonorepo) problems.push(`${rel}: citation escapes the drop: \`${m[1]}\``);
    }
    for (const m of text.matchAll(DROP_BARE_MD)) {
      const name = m[1];
      if (name.includes("/") || name.includes("<") || name.includes("*")) continue;
      if (!known.has(name)) problems.push(`${rel}: cited filename exists nowhere (drop or monorepo): \`${name}\``);
    }
  }
  return problems;
}

function runVendor(mode, dest) {
  const files = vendorSet();
  const problems = vendorClosureProblems(files);
  if (mode === "vendor-check") {
    if (problems.length) {
      console.log(`ssdt-agent vendor drop: ${problems.length} problem(s) — the drop is not citation-closed`);
      for (const p of problems) console.log(`  ${p}`);
      process.exit(1);
    }
    console.log(`ssdt-agent vendor drop: ${files.size} files, citation-closed`);
    return;
  }
  if (problems.length) {
    console.log("refusing to stage an unclosed drop; run vendor-check for the findings");
    process.exit(1);
  }
  const out = dest ?? join(TREE, "vendor-drop");
  rmSync(out, { recursive: true, force: true });
  for (const [rel, src] of files) {
    const t = join(out, rel);
    mkdirSync(dirname(t), { recursive: true });
    writeFileSync(t, readFileSync(src));
  }
  // The manifest is deterministic per source commit (the committed-at
  // stamp, never a wall clock), so an unchanged re-publish is a byte-level
  // no-op — the idempotent-update contract.
  let commit = "unknown";
  let committedAt = "unknown";
  try {
    commit = execFileSync("git", ["-C", REPO, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
    committedAt = execFileSync("git", ["-C", REPO, "show", "-s", "--format=%cI", "HEAD"], { encoding: "utf8" }).trim();
  } catch { /* the manifest degrades to "unknown" outside a work tree */ }
  writeFileSync(
    join(out, "VENDOR.json"),
    JSON.stringify(
      { source: "danielbdyer/outsystems-ddl-exporter", path: "sidecar/projection/ssdt-agent", commit,
        sourceCommittedAtUtc: committedAt, files: files.size },
      null, 2) + "\n"
  );
  console.log(`staged ${files.size} files + VENDOR.json into ${relative(REPO, out)}/`);
}

function main() {
  const mode = process.argv[2] ?? "check";
  if (mode === "copilot-apply" || mode === "copilot-check") return runCopilot(mode);
  if (mode === "estate-kit-apply" || mode === "estate-kit-check") return runEstateKit(mode);
  if (mode === "vendor-apply" || mode === "vendor-check") return runVendor(mode, process.argv[3]);

  const expected = new Map();
  for (const s of sources()) expected.set(target(s), rendered(s));

  if (mode === "apply") {
    for (const [t, content] of expected) {
      mkdirSync(dirname(t), { recursive: true });
      writeFileSync(t, content);
    }
    console.log(`packaged ${expected.size} entries into .claude/`);
    return;
  }

  const problems = [];
  for (const [t, content] of expected) {
    if (!existsSync(t)) problems.push(`missing package: ${relative(REPO, t)}`);
    else if (readFileSync(t, "utf8") !== content)
      problems.push(`stale package (re-run \`ssdt-agent-package.mjs apply\`): ${relative(REPO, t)}`);
  }
  // Orphans: generated files (either generation's marker) whose source is gone.
  const marker = "ssdt-agent-package";
  const packaged = [
    ...walk(join(DOT, "skills")).filter((p) => basename(p) === "SKILL.md"),
    ...walk(join(DOT, "agents")).filter((p) => p.endsWith(".md")),
  ];
  for (const t of packaged) {
    if (!expected.has(t) && readFileSync(t, "utf8").includes(marker))
      problems.push(`orphan package (source gone): ${relative(REPO, t)}`);
  }
  if (problems.length) {
    console.log(`ssdt-agent packaging: ${problems.length} problem(s)`);
    for (const p of problems) console.log(`  ${p}`);
    process.exit(1);
  }
  console.log(`ssdt-agent packaging: ${expected.size} entries in sync`);
}

main();
