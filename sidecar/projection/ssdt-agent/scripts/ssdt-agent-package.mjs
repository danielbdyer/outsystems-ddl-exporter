#!/usr/bin/env node
// Package the ssdt-agent tree as loadable agent surfaces — apply | check |
// copilot-apply | copilot-check | vendor <dest>.
//
// CONNECTORS.md §1 and §2, executed with the repo's regenerate-and-diff
// discipline instead of raw copies: each packaged entry is a POINTER — the
// source file's frontmatter verbatim (the `description` is the dispatch
// surface an agent triggers on) plus a short body that routes to the canonical
// in-tree file. One canonical body, working relative citations, no drift
// surface beyond the frontmatter — and the `packaging` gate
// (ssdt-agent-gates.mjs) fails CI whenever source and package disagree.
//
//   apply           (re)generate .claude/skills/<name>/SKILL.md for every
//                   skills/**/SKILL.md, and .claude/agents/<name>.md for
//                   every agents/*.md
//   check           exit 1 if the packaged set is missing, stale, or orphaned
//   copilot-apply   (re)generate the GitHub Copilot bundle (see below)
//   copilot-check   exit 1 if that bundle is missing, stale, or orphaned
//
// `skills/operations/*.md` are knowledge files, not skills, and are never
// packaged (CONNECTORS.md §1's explicit carve-out). `skills/INDEX.md` is
// generated by copilot-apply and is not a skill either.
//
// This script lives INSIDE the tree (ssdt-agent/scripts/) so it travels with
// a vendored copy. It detects its layout:
//   - source monorepo: the tree sits at sidecar/projection/ssdt-agent/; the
//     Copilot bundle is staged into ssdt-agent/copilot-package/.
//   - vendored estate repo: the tree sits at ssdt-agent/ in the repo root;
//     copilot-apply stages the bundle AND writes the .github/ + .azuredevops/
//     files in place at the repo root (copilot-check verifies both).
//
// Node ≥ 18, zero dependencies. Run from anywhere; paths resolve from this
// file's location.

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join, relative, basename, sep } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const TREE = dirname(HERE);                    // .../ssdt-agent
const MONOREPO =
  basename(dirname(TREE)) === "projection" && basename(dirname(dirname(TREE))) === "sidecar";
const REPO = MONOREPO ? dirname(dirname(dirname(TREE))) : dirname(TREE);
const DOT = join(REPO, ".claude");

// Path of this script from the repo root, for the .claude pointer bodies
// (monorepo: sidecar/projection/ssdt-agent/scripts/…; estate: ssdt-agent/scripts/…).
const SCRIPT_FROM_REPO = relative(REPO, join(HERE, "ssdt-agent-package.mjs"));

const FRONT = /^---\n([\s\S]*?\n)---\n/;

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

function* sources() {
  for (const p of walk(join(TREE, "skills")).filter((p) => basename(p) === "SKILL.md").sort()) {
    yield { kind: "skill", name: basename(dirname(p)), src: p, rel: relative(REPO, p) };
  }
  for (const p of walk(join(TREE, "agents")).filter((p) => p.endsWith(".md")).sort()) {
    yield { kind: "agent", name: basename(p, ".md"), src: p, rel: relative(REPO, p) };
  }
}

function frontmatter(path) {
  const m = FRONT.exec(readFileSync(path, "utf8"));
  if (!m) { console.error(`no frontmatter in ${path}`); process.exit(1); }
  return m[1];
}

// The description's leading clause — the trigger phrases, in the developer's
// own words — for the dispatch index. First " — " segment, capped.
function descClause(fm) {
  const m = /^description: (.*)$/m.exec(fm);
  if (!m) return "";
  let d = m[1];
  if (d.startsWith('"')) {
    try { d = JSON.parse(d); } catch { d = d.slice(1, -1).replace(/\\(.)/g, "$1"); }
  }
  const clause = d.split(" — ")[0];
  return clause.length > 220 ? clause.slice(0, 217) + "…" : clause;
}

function rendered({ kind, src, rel }) {
  const fm = frontmatter(src);
  const body =
    kind === "skill"
      ? `The canonical skill body lives in the tree, where its relative citations resolve:\n` +
        `**Read \`${rel}\` now and follow it exactly.** This package is the dispatch pointer\n` +
        `(generated by \`${SCRIPT_FROM_REPO} apply\`; do not edit by hand).\n`
      : `Adopt the role defined at \`${rel}\` — **Read that file now and follow it exactly**,\n` +
        `then proceed with the task you were given. This package is the dispatch pointer\n` +
        `(generated by \`${SCRIPT_FROM_REPO} apply\`; do not edit by hand).\n`;
  return `---\n${fm}---\n\n${body}`;
}

function target({ kind, name }) {
  return kind === "skill" ? join(DOT, "skills", name, "SKILL.md") : join(DOT, "agents", name + ".md");
}

