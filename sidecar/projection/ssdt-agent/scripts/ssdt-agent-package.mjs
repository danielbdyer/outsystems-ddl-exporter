// The ten-section schema-change PR template, emitted for both hosts from the
// tree's canonical mirror (pr-template/schema-change.md, which mirrors
// skills/author-pr/SKILL.md).
function prTemplateSource() {
  const p = join(TREE, "pr-template", "schema-change.md");
  if (!existsSync(p)) {
    console.error(`missing PR-template source: ${relative(REPO, p)}`);
    process.exit(1);
  }
  return GEN + "\n" + readFileSync(p, "utf8");
}

// skills/INDEX.md — the one-hop dispatch table for agents without native skill
// discovery: slug → trigger phrases → owning file. Grouped by skill family.
function indexDoc() {
  const groups = { op: [], _index: [], review: [], capability: [] };
  for (const s of sources()) {
    if (s.kind !== "skill") continue;
    const relTree = relative(TREE, s.src);               // skills/op/add-check/SKILL.md
    const parts = relTree.split(sep);                    // [skills, op, add-check, SKILL.md]
    const family = parts.length === 4 ? parts[1] : "capability";
    const row = `- \`${s.name}\` — ${descClause(frontmatter(s.src))} → \`${relTree.split(sep).join("/")}\``;
    (groups[family] ?? groups.capability).push(row);
  }
  return [
    GEN, "",
    "# Skill dispatch index", "",
    "One row per skill: the trigger phrases (the developer's own words) and the file that owns the",
    "full skill. For an agent without native skill discovery — GitHub Copilot in Visual Studio 2022,",
    "or any editor that only reads instruction files — this is the one-hop route: find the matching",
    "row, read that skill file, follow it. Paths are relative to this tree's root (`" + VENDOR + "/`",
    "when the tree is vendored in the estate repository).", "",
    "## Operations (the catalog — one per schema change)", "",
    ...groups.op, "",
    "## Capabilities (the working skills the operations compose)", "",
    ...groups.capability, "",
    "## Shared knowledge (cross-cutting; per-op skills point here)", "",
    ...groups._index, "",
    "## Review (Persona 2 — the adversarial reviewer)", "",
    ...groups.review, "",
  ].join("\n");
}

