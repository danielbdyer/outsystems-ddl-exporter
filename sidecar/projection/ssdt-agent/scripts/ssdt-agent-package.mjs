function copilotExpected() {
  const exp = new Map();
  for (const s of sources()) {
    const t =
      s.kind === "skill"
        ? join(COPILOT, ".github", "skills", s.name, "SKILL.md")
        : join(COPILOT, ".github", "agents", s.name + ".agent.md");
    exp.set(t, s.kind === "skill" ? copilotSkill(s) : copilotAgent(s));
  }
  exp.set(join(COPILOT, ".github", "copilot-instructions.md"), routerDoc());
  for (const [fname, content] of instructionDocs())
    exp.set(join(COPILOT, ".github", "instructions", fname), content);
  for (const [fname, content] of promptDocs())
    exp.set(join(COPILOT, ".github", "prompts", fname), content);
  const template = prTemplateSource();
  exp.set(join(COPILOT, ".github", "PULL_REQUEST_TEMPLATE", "schema-change.md"), template);
  exp.set(join(COPILOT, ".azuredevops", "pull_request_template", "schema-change.md"), template);
  exp.set(join(COPILOT, "ADOPTION.md"), adoptionDoc());
  exp.set(join(TREE, "skills", "INDEX.md"), indexDoc());

  // Vendored (estate) layout: the .github/ + .azuredevops/ portions also live
  // at the repository root, written and checked in place.
  if (!MONOREPO) {
    for (const [t, content] of [...exp]) {
      const rel = relative(COPILOT, t);
      if (rel.startsWith(".github" + sep) || rel.startsWith(".azuredevops" + sep)) {
        exp.set(join(REPO, rel), content);
      }
    }
  }
  return exp;
}

function runCopilot(mode) {
  const expected = copilotExpected();
  if (mode === "copilot-apply") {
    for (const [t, content] of expected) {
      mkdirSync(dirname(t), { recursive: true });
      writeFileSync(t, content);
    }
    console.log(`packaged ${expected.size} entries into ${relative(REPO, COPILOT)}/` +
      (MONOREPO ? "" : " and the repository root (vendored layout)"));
    return;
  }
  const problems = [];
  for (const [t, content] of expected) {
    if (!existsSync(t)) problems.push(`missing: ${relative(REPO, t)}`);
    else if (readFileSync(t, "utf8") !== content)
      problems.push(`stale (re-run \`ssdt-agent-package.mjs copilot-apply\`): ${relative(REPO, t)}`);
  }
  const marker = "ssdt-agent-package";
  for (const p of walk(COPILOT)) {
    if (!expected.has(p) && readFileSync(p, "utf8").includes(marker))
      problems.push(`orphan (source gone): ${relative(REPO, p)}`);
  }
  if (problems.length) {
    console.log(`ssdt-agent copilot package: ${problems.length} problem(s)`);
    for (const p of problems) console.log(`  ${p}`);
    process.exit(1);
  }
  console.log(`ssdt-agent copilot package: ${expected.size} entries in sync`);
}

// Program history of the source repository: safe to prune from a vendored copy — nothing
// functional cites it. Kept in one place so ADOPTION.md's prose and the vendor verb agree.
const VENDOR_PRUNE = new Set([
  "ASSESSMENT_2026_08_24.md",
  "ARCHITECTURE_REVIEW_2026_08_28.md",
  "ENABLEMENT_PROGRAM.md",
  "HANDOFF_SESSION_2026_08_26.md",
  "PHASE_2_CURRICULUM.md",
  "ACCELERANT_PLAN.md",
  "CLAUDE.md",
]);
const VENDOR_SKIP_DIRS = new Set(["bin", "obj", "node_modules", ".git"]);

function runVendor(dest) {
  if (!dest) {
    console.log("usage: ssdt-agent-package.mjs vendor <estate-repo-root>");
    process.exit(1);
  }
  const destRoot = join(dest, VENDOR);
  let copied = 0, pruned = 0;
  const copyDir = (from, to, depth) => {
    for (const name of readdirSync(from)) {
      const src = join(from, name);
      const isDir = statSync(src).isDirectory();
      if (isDir && VENDOR_SKIP_DIRS.has(name)) continue;
      if (depth === 0 && !isDir && VENDOR_PRUNE.has(name)) { pruned++; continue; }
      const tgt = join(to, name);
      if (isDir) { copyDir(src, tgt, depth + 1); continue; }
      mkdirSync(dirname(tgt), { recursive: true });
      writeFileSync(tgt, readFileSync(src));
      copied++;
    }
  };
  copyDir(TREE, destRoot, 0);
  console.log(`vendored ${copied} files into ${destRoot} (${pruned} program-history files pruned)`);
  console.log(`next: from ${dest}, run \`node ${VENDOR}/scripts/ssdt-agent-package.mjs copilot-apply\``);
  console.log(`      to write the .github/ and .azuredevops/ bundles in place, then follow ADOPTION.md.`);
}

function main() {
  const mode = process.argv[2] ?? "check";
  if (mode === "vendor") return runVendor(process.argv[3]);
  if (mode === "copilot-apply" || mode === "copilot-check") return runCopilot(mode);

  const expected = new Map();
  for (const s of sources()) expected.set(target(s), rendered(s));

  if (mode === "apply") {
    for (const [t, content] of expected) {
      mkdirSync(dirname(t), { recursive: true });
      writeFileSync(t, content);
    }
    console.log(`packaged ${expected.size} entries into .claude/`);
    return;
  }

  const problems = [];
  for (const [t, content] of expected) {
    if (!existsSync(t)) problems.push(`missing package: ${relative(REPO, t)}`);
    else if (readFileSync(t, "utf8") !== content)
      problems.push(`stale package (re-run \`ssdt-agent-package.mjs apply\`): ${relative(REPO, t)}`);
  }
  // Orphans: generated files (either generation's marker) whose source is gone.
  const marker = "ssdt-agent-package";
  const packaged = [
    ...walk(join(DOT, "skills")).filter((p) => basename(p) === "SKILL.md"),
    ...walk(join(DOT, "agents")).filter((p) => p.endsWith(".md")),
  ];
  for (const t of packaged) {
    if (!expected.has(t) && readFileSync(t, "utf8").includes(marker))
      problems.push(`orphan package (source gone): ${relative(REPO, t)}`);
  }
  if (problems.length) {
    console.log(`ssdt-agent packaging: ${problems.length} problem(s)`);
    for (const p of problems) console.log(`  ${p}`);
    process.exit(1);
  }
  console.log(`ssdt-agent packaging: ${expected.size} entries in sync`);
}

main();
