  "or the generator and re-run. -->";

// Content fingerprint over the generator and every source input — deterministic,
// so `copilot-check` stays byte-exact; it changes exactly when regeneration is due.
function fingerprint() {
  const h = createHash("sha256");
  h.update(readFileSync(join(HERE, "ssdt-agent-package.mjs")));
  const prTemplate = join(TREE, "pr-template", "schema-change.md");
  if (existsSync(prTemplate)) h.update(readFileSync(prTemplate));
  for (const s of sources()) h.update(readFileSync(s.src));
  return h.digest("hex").slice(0, 12);
}

